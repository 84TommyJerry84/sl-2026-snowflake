-- 1. Warehouse
CREATE WAREHOUSE IF NOT EXISTS NYC_TAXI_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- 2. Base
CREATE DATABASE IF NOT EXISTS NYC_TAXI_DB;

-- 3. Schémas
CREATE SCHEMA IF NOT EXISTS NYC_TAXI_DB.RAW;
CREATE SCHEMA IF NOT EXISTS NYC_TAXI_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS NYC_TAXI_DB.FINAL;

-- 4. Contexte
USE WAREHOUSE NYC_TAXI_WH;
USE DATABASE NYC_TAXI_DB;
USE SCHEMA RAW;

-- 5. Vérification du contexte
SELECT CURRENT_WAREHOUSE(), CURRENT_DATABASE(), CURRENT_SCHEMA();

-- 6. Stage interne utilisé pour le chargement
CREATE STAGE IF NOT EXISTS NYC_TAXI_DB.RAW.NYC_TAXI_STAGE;

-- 7. Format Parquet
CREATE FILE FORMAT IF NOT EXISTS NYC_TAXI_DB.RAW.NYC_TAXI_PARQUET_FORMAT
    TYPE = PARQUET
    USE_LOGICAL_TYPE = TRUE;

ALTER FILE FORMAT NYC_TAXI_DB.RAW.NYC_TAXI_PARQUET_FORMAT
SET USE_LOGICAL_TYPE = TRUE;

-- 8. Vérifications
SHOW STAGES IN SCHEMA NYC_TAXI_DB.RAW;
LIST @NYC_TAXI_DB.RAW.NYC_TAXI_STAGE;
