-- Initialisation de l'infrastructure Snowflake
-- Remplacer <AWS_ROLE_ARN> et <BUCKET_NAME> par les valeurs de l'environnement.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS NYC_TAXI_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS NYC_TAXI_DB;

CREATE SCHEMA IF NOT EXISTS NYC_TAXI_DB.RAW;
CREATE SCHEMA IF NOT EXISTS NYC_TAXI_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS NYC_TAXI_DB.FINAL;

USE WAREHOUSE NYC_TAXI_WH;
USE DATABASE NYC_TAXI_DB;
USE SCHEMA RAW;

SELECT
    CURRENT_WAREHOUSE(),
    CURRENT_DATABASE(),
    CURRENT_SCHEMA();

CREATE FILE FORMAT IF NOT EXISTS NYC_TAXI_DB.RAW.NYC_TAXI_PARQUET_FORMAT
    TYPE = PARQUET
    USE_LOGICAL_TYPE = TRUE;

CREATE STORAGE INTEGRATION IF NOT EXISTS NYC_TAXI_S3_INTEGRATION
    TYPE = EXTERNAL_STAGE
    STORAGE_PROVIDER = 'S3'
    ENABLED = TRUE
    STORAGE_AWS_ROLE_ARN = '<AWS_ROLE_ARN>'
    STORAGE_ALLOWED_LOCATIONS = (
        's3://<BUCKET_NAME>/nyc_taxi/'
    );

-- Après la création :
-- DESC INTEGRATION NYC_TAXI_S3_INTEGRATION;
--
-- Reporter STORAGE_AWS_IAM_USER_ARN
-- et STORAGE_AWS_EXTERNAL_ID
-- dans la relation de confiance du rôle IAM AWS.

CREATE STAGE IF NOT EXISTS NYC_TAXI_DB.RAW.NYC_TAXI_EXT_STAGE
    URL = 's3://<BUCKET_NAME>/nyc_taxi/'
    STORAGE_INTEGRATION = NYC_TAXI_S3_INTEGRATION;

SHOW STAGES IN SCHEMA NYC_TAXI_DB.RAW;

LIST @NYC_TAXI_DB.RAW.NYC_TAXI_EXT_STAGE;