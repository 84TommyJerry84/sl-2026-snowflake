USE WAREHOUSE NYC_TAXI_WH;
USE DATABASE NYC_TAXI_DB;
USE SCHEMA RAW;

CREATE FILE FORMAT IF NOT EXISTS NYC_TAXI_DB.RAW.NYC_TAXI_CSV_FORMAT
    TYPE = CSV
    PARSE_HEADER = TRUE
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    TRIM_SPACE = TRUE;

-- Les noms de colonnes suivent le header du CSV pour permettre MATCH_BY_COLUMN_NAME
CREATE OR REPLACE TABLE NYC_TAXI_DB.RAW.TAXI_ZONES (
    LocationID NUMBER,
    Borough VARCHAR,
    Zone VARCHAR,
    service_zone VARCHAR
);

-- Chargement du référentiel depuis le stage externe S3
COPY INTO NYC_TAXI_DB.RAW.TAXI_ZONES
FROM @NYC_TAXI_DB.RAW.NYC_TAXI_EXT_STAGE/reference/taxi_zone_lookup.csv
FILE_FORMAT = (
    FORMAT_NAME = 'NYC_TAXI_DB.RAW.NYC_TAXI_CSV_FORMAT'
)
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

SELECT COUNT(*) AS taxi_zone_rows
FROM NYC_TAXI_DB.RAW.TAXI_ZONES;

SELECT *
FROM NYC_TAXI_DB.RAW.TAXI_ZONES
ORDER BY LocationID
LIMIT 10;
